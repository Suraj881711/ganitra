def _build_aliases():
    out = []
    seen = set()
    for cls in sorted(TOPICS_BY_CLASS_BANDB):
        for topic in TOPICS_BY_CLASS_BANDB[cls]:
            out.append((topic["name"].lower(), topic["slug"]))
    out.extend(_ALIAS_EXTRAS_BANDB)
    deduped = []
    for phrase, slug in out:
        if phrase in seen:
            continue
        seen.add(phrase)
        deduped.append((phrase, slug))
    return deduped


ALIASES_BANDB = _build_aliases()

